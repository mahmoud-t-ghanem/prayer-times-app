let lang = localStorage.getItem("lang") === "en" ? "en" : "ar";
const listeners = new Set();

export const getLang = () => lang;
export const locale = () => (lang === "ar" ? "ar-u-nu-latn" : "en-US");
export const pick = (obj) => obj[lang];

export function t(key, vars = {}) {
  const str = dict[lang][key] ?? dict.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-tip]").forEach((el) => {
    const text = t(el.dataset.i18nTip);
    el.dataset.tip = text;
    el.setAttribute("aria-label", text);
  });
  const titleKey = document.documentElement.dataset.title;
  if (titleKey) document.title = t(titleKey);
}

export function onLangChange(fn) {
  listeners.add(fn);
}

export function setLang(next) {
  lang = next === "en" ? "en" : "ar";
  localStorage.setItem("lang", lang);
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  applyTranslations();
  listeners.forEach((fn) => fn(lang));
}

export const toggleLang = () => setLang(lang === "ar" ? "en" : "ar");
